-- Suivi des mouvements de stock (Oracle)
-- Pas de SEQUENCE : l'application calcule le prochain id (MAX + 1).
-- A lancer APRES les scripts qui creent EMPLOYE et MATERIEL.

CREATE TABLE MOUVEMENT_STOCK (
    ID_MOUVEMENT    NUMBER         PRIMARY KEY,
    ID_MATERIEL     NUMBER         NOT NULL REFERENCES MATERIEL(ID_MATERIEL),
    ID_EMPLOYE      NUMBER         NOT NULL REFERENCES EMPLOYE(ID_EMPLOYE),
    TYPE_MOUVEMENT  VARCHAR2(10)   NOT NULL CHECK (TYPE_MOUVEMENT IN ('ENTREE', 'SORTIE')),
    QUANTITE        NUMBER(8)      NOT NULL CHECK (QUANTITE > 0),
    DATE_MOUVEMENT  DATE           DEFAULT SYSDATE NOT NULL,
    MOTIF           VARCHAR2(200)  NOT NULL
);

CREATE INDEX IDX_MVT_MATERIEL ON MOUVEMENT_STOCK(ID_MATERIEL, DATE_MOUVEMENT);
