-- AXIS Vehicules - schema Oracle
-- À exécuter une seule fois dans SQL Developer avec le compte propriétaire de l'application.
-- Les tables et colonnes correspondent aux requêtes de vehicule.cpp et entretien.cpp.

CREATE TABLE VEHICULE (
    ID_VEHICULE NUMBER(10)       NOT NULL,
    IMMATRICULATION VARCHAR2(20 CHAR) NOT NULL,
    TYPE VARCHAR2(60 CHAR)      NOT NULL,
    KILOMETRAGE NUMBER(10)      DEFAULT 0 NOT NULL,
    ETAT VARCHAR2(30 CHAR)      NOT NULL,
    DISPONIBILITE VARCHAR2(30 CHAR) NOT NULL,
    DATE_DERNIERE_MAINTENANCE DATE,
    DATE_PROCHAINE_MAINTENANCE DATE,
    DATE_EXPIRATION_ASSURANCE DATE,
    DATE_VISITE_TECHNIQUE DATE,
    CONSTRAINT PK_VEHICULE PRIMARY KEY (ID_VEHICULE),
    CONSTRAINT UK_VEHICULE_IMMATRICULATION UNIQUE (IMMATRICULATION),
    CONSTRAINT CK_VEHICULE_KM CHECK (KILOMETRAGE BETWEEN 0 AND 2000000),
    CONSTRAINT CK_VEHICULE_TYPE CHECK (TYPE IN (
        'Camion-citerne', 'Ambulance', 'Échelle aérienne', 'Fourgon pompe', 'Véhicule léger'
    )),
    CONSTRAINT CK_VEHICULE_ETAT CHECK (ETAT IN ('Bon', 'À surveiller', 'Hors service')),
    CONSTRAINT CK_VEHICULE_DISPO CHECK (DISPONIBILITE IN (
        'Disponible', 'En intervention', 'En maintenance'
    ))
);

CREATE TABLE ENTRETIEN_VEHICULE (
    ID_ENTRETIEN NUMBER(10)       NOT NULL,
    ID_VEHICULE NUMBER(10)        NOT NULL,
    TYPE_ENTRETIEN VARCHAR2(60 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    DATE_PREVUE DATE              NOT NULL,
    KM_PREVU NUMBER(10)           DEFAULT 0 NOT NULL,
    STATUT VARCHAR2(20 CHAR)      DEFAULT 'Planifié' NOT NULL,
    GARAGE VARCHAR2(120 CHAR),
    DATE_REALISEE DATE,
    KM_REALISE NUMBER(10)         DEFAULT 0 NOT NULL,
    COUT NUMBER(12,2)             DEFAULT 0 NOT NULL,
    PROCHAINE_DATE DATE,
    PROCHAIN_KM NUMBER(10)        DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ENTRETIEN_VEHICULE PRIMARY KEY (ID_ENTRETIEN),
    CONSTRAINT FK_ENT_VEHICULE FOREIGN KEY (ID_VEHICULE)
        REFERENCES VEHICULE (ID_VEHICULE),
    CONSTRAINT CK_ENTRETIEN_STATUT CHECK (STATUT IN ('Planifié', 'En retard', 'Terminé')),
    CONSTRAINT CK_ENTRETIEN_KM CHECK (KM_PREVU >= 0 AND KM_REALISE >= 0 AND PROCHAIN_KM >= 0),
    CONSTRAINT CK_ENTRETIEN_COUT CHECK (COUT >= 0)
);

-- La classe GestionEntretiens utilise cette séquence pour créer les entretiens.
CREATE SEQUENCE SEQ_ENTRETIEN_VEHICULE
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE INDEX IDX_ENTRETIEN_VEHICULE_ID ON ENTRETIEN_VEHICULE (ID_VEHICULE);
CREATE INDEX IDX_ENTRETIEN_DATE_STATUT ON ENTRETIEN_VEHICULE (STATUT, DATE_PREVUE);
CREATE INDEX IDX_VEHICULE_DATE_MAINT ON VEHICULE (DATE_PROCHAINE_MAINTENANCE);

-- Vérification rapide après exécution.
SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('VEHICULE', 'ENTRETIEN_VEHICULE')
ORDER BY TABLE_NAME;
